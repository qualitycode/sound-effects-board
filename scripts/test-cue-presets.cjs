const assert = require('assert/strict');
const fs = require('fs');
const path = require('path');
const { resolvePresets, sanitizeAction } = require('../cue-presets');
const root = path.join(__dirname, '..');
const script = JSON.parse(fs.readFileSync(path.join(root, 'assets/playScript/script.json')));
const pack = JSON.parse(fs.readFileSync(path.join(root, 'soundpack/pack.json')));
const pads = pack.pads.map((p, i) => ({ ...p, id: `test-${i}`, sound: p.file }));
const assignments = resolvePresets(script, pads);
assert.equal(Object.keys(assignments).length, 95);
assert.ok(Object.values(assignments).every(actions => actions.length && actions.every(a => pads.some(p => p.id === a.padId))));
assert.equal(assignments['p12-c1'][0].repeat, 3);
assert.equal(assignments['p15-c3'].find(a => a.repeat === 5).action, 'play');
assert.equal(assignments['p47-c1'][0].repeat, 9);
assert.ok(assignments['p15-c1'].some(a => a.delay === 2 && a.action === 'stop'));
assert.equal(assignments['p21-c1'][0].action, 'hold');
assert.ok(assignments['p31-c1'].filter(a => a.action === 'fade').length >= 6);
assert.equal(resolvePresets(script, pads, { 'p12-c1': [] })['p12-c1'].length, 0, 'intentional cleared cues stay cleared');
assert.equal(resolvePresets(script, pads, { 'p12-c1': [{ padId: 'custom', action: 'play' }] })['p12-c1'][0].padId, 'custom', 'saved assignments take precedence');
assert.ok(resolvePresets(script, [])["p12-c1"].some(a => !a.padId), 'missing sounds stay unresolved');
assert.deepEqual(sanitizeAction({ padId: 'a', action: 'unsafe', repeat: 999, delay: -1 }), { padId: 'a', action: 'play', repeat: 12, delay: 0 });
for (const p of pack.pads) assert.ok(fs.existsSync(path.join(root, 'soundpack', p.file)), p.file);
console.log('All 95 cues resolve to existing sound files; counts, delays, continuing loops, scene fades, and overrides verified.');
