// Run with the project's Electron binary; uses a throwaway browser profile.
const { app, BrowserWindow } = process.env.ELECTRON_RUN_AS_NODE ? require('./chrome-test-driver.cjs') : require('electron');
const fs = require('fs');
const path = require('path');
const os = require('os');
const assert = require('assert/strict');
const results = path.join(__dirname, 'test-results');
fs.mkdirSync(results, { recursive: true });
const logPath = path.join(results, 'integration.log');
fs.writeFileSync(logPath, '');
const log = line => fs.appendFileSync(logPath, line + '\n');
app.setPath('userData', fs.mkdtempSync(path.join(os.tmpdir(), 'soundboard-browser-test-')));
const errors = [];
let win;
const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
const js = code => win.webContents.executeJavaScript(code, true);
const check = (value, message) => { assert.ok(value, message); log('PASS ' + message); };
const finish = code => { clearTimeout(watchdog); app.exit(code); };
const watchdog = setTimeout(() => { log('FAIL: test timed out'); finish(1); }, 90000);
process.on('uncaughtException', err => { log(err.stack); finish(1); });
app.whenReady().then(async () => {
  try {
    win = new BrowserWindow({ show: false, width: 1400, height: 1000, webPreferences: { contextIsolation: true, nodeIntegration: false, backgroundThrottling: false } });
    win.webContents.on('console-message', (_event, details) => { if (details.level === 'error') errors.push(details.message); });
    await win.loadURL('http://127.0.0.1:8765');
    await js('window.browserProject.ready');
    for (let i = 0; i < 100 && !await js("document.querySelectorAll('.script-cue').length === 95"); i++) await sleep(100);
    check(await js("document.querySelectorAll('#board .pad').length === 64"), 'all 64 saved sound IDs imported');
    check(await js("document.querySelectorAll('.script-cue').length === 95"), 'all 95 cues imported');
    check(await js("document.querySelectorAll('#scriptText section').length === 41"), 'all 41 script pages imported');
    check(await js("window.browserProject.snapshot().assignments['p12-c1'][0].repeat === 3"), 'saved cue actions preserved');
    await js(`window.__gains = []; const originalGain = AudioContext.prototype.createGain;
      AudioContext.prototype.createGain = function() { const gain = originalGain.call(this); window.__gains.push(gain); return gain; };
      document.querySelector('#board [data-id="6b5bea18-6141-45af-9484-b2c9242543ac"]').click();`);
    await sleep(200);
    check(await js("document.querySelectorAll('#board .playing').length === 1"), 'loop starts in browser audio engine');
    await js("document.getElementById('stopAll').click()");
    check(await js("document.querySelectorAll('#board .playing').length === 0"), 'Stop All stops loop');
    await js("document.getElementById('peopleBtn').click()");
    await sleep(50);
    await js(`document.getElementById('addPerson').click();
      document.querySelector('#peopleRows input[type=text]').value = 'Piano / Reader';
      document.querySelector('#peopleRows input[type=color]').value = '#4488cc';
      document.getElementById('peopleForm').requestSubmit();`);
    await sleep(100);
    check(await js("window.browserProject.snapshot().people.length === 1"), 'people saved with stable IDs');
    await js("document.getElementById('editToggle').click(); document.getElementById('scriptView').click(); document.querySelector('.edit-passage').click()");
    await js(`document.getElementById('passageText').value = 'A rehearsal passage edited in the browser.';
      document.getElementById('passageNote').value = 'Pause here for the piano.';
      document.getElementById('passagePerson').selectedIndex = 1;
      document.getElementById('passageColor').value = '#aaffcc';
      document.getElementById('passageForm').requestSubmit();`);
    await sleep(100);
    check(await js("document.querySelector('.dialogue').textContent.includes('A rehearsal passage') && document.querySelector('.dialogue .reader-label').textContent === 'Piano / Reader'"), 'script text and reader assignment rendered');
    check(await js("[...document.querySelectorAll('[data-passage-note]')].some(n => n.textContent === 'Pause here for the piano.' && n.style.backgroundColor === 'rgb(170, 255, 204)')"), 'colored script notes rendered');
    // A short real WAV exercises natural end/repeat rather than simulating ended events.
    await js(`(async () => {
      const rate = 8000, frames = 800, wav = new ArrayBuffer(44 + frames * 2), v = new DataView(wav);
      const text = (at, s) => [...s].forEach((c, i) => v.setUint8(at + i, c.charCodeAt(0)));
      text(0, 'RIFF'); v.setUint32(4, 36 + frames * 2, true); text(8, 'WAVE'); text(12, 'fmt ');
      v.setUint32(16, 16, true); v.setUint16(20, 1, true); v.setUint16(22, 1, true);
      v.setUint32(24, rate, true); v.setUint32(28, rate * 2, true); v.setUint16(32, 2, true); v.setUint16(34, 16, true);
      text(36, 'data'); v.setUint32(40, frames * 2, true);
      for (let i = 0; i < frames; i++) v.setInt16(44 + i * 2, Math.sin(i / 8) * 1000, true);
      const picked = await window.api.saveRecording(wav);
      const originalPick = window.api.pickMedia; window.api.pickMedia = async () => picked;
      document.getElementById('addBtn').click(); document.getElementById('fSoundPick').click();
      await new Promise(r => setTimeout(r, 50)); window.api.pickMedia = originalPick;
      document.getElementById('fLabel').value = 'Test Pulse'; document.getElementById('fPerson').selectedIndex = 1;
      document.getElementById('editorForm').requestSubmit();
    })()`);
    await sleep(100);
    check(await js("window.browserProject.snapshot().pads.some(p => p.label === 'Test Pulse' && p.personId)"), 'uploaded sound saved with person assignment');
    await js(`document.querySelector('[data-cue-id="p12-c1"]').click();
      document.getElementById('cueName').value = 'Three test pulses'; document.getElementById('cueKey').value = '!';
      document.getElementById('cuePerson').selectedIndex = 1; document.getElementById('cueVolume').value = 80;
      document.getElementById('cueNote').value = 'Watch the conductor.'; document.getElementById('cueNoteColor').value = '#aaffcc';
      document.querySelector('.cue-pad').value = window.browserProject.snapshot().pads.find(p => p.label === 'Test Pulse').id;
      document.querySelector('.cue-level').value = 50; document.querySelector('.cue-repeat').value = 3;
      document.getElementById('cueForm').requestSubmit();`);
    await sleep(100);
    check(await js("document.querySelector('[data-cue-id=\"p12-c1\"]').textContent.includes('Three test pulses')"), 'named cue reflected in script');
    check(await js(`document.querySelector('.script-cue[data-cue-id="p12-c1"]').textContent.includes('Piano / Reader · Key !') && document.querySelector('[data-note-for="p12-c1"]').textContent === 'Watch the conductor.' && document.querySelector('[data-note-for="p12-c1"]').style.backgroundColor === 'rgb(170, 255, 204)'`), 'script cue shows person, shortcut and saved highlighted note');
    await js(`document.getElementById('padsView').click(); document.querySelector('#board .pad').click();
      document.getElementById('fKey').dispatchEvent(new KeyboardEvent('keydown', {key:'!', bubbles:true}));
      document.getElementById('editorForm').requestSubmit();`);
    check(await js(`document.getElementById('editor').open && document.getElementById('editorError').textContent.includes('used by a cue')`), 'sound editor rejects a cue shortcut collision');
    await js(`document.getElementById('fCancel').click(); document.getElementById('scriptView').click();
      document.querySelector('.script-cue[data-cue-id="p12-c1"]').click();
      document.getElementById('cueKey').value = window.browserProject.snapshot().pads.find(p => p.key).key;
      document.getElementById('cueForm').requestSubmit();`);
    check(await js(`document.getElementById('cueEditor').open && document.getElementById('cueError').textContent.includes('used by sound')`), 'cue editor rejects a sound shortcut collision');
    await js(`document.getElementById('cancelCue').click()`);
    await js(`document.getElementById('cuesView').click();
      window.__playCalls = 0; const originalPlay = HTMLMediaElement.prototype.play;
      HTMLMediaElement.prototype.play = function() { window.__playCalls++; return originalPlay.call(this); };
      document.getElementById('editToggle').click();
      document.querySelector('#cueBoard [data-cue-id="p12-c1"]').click();`);
    await sleep(80);
    check(await js("Math.abs(window.__gains.at(-1).gain.value - .4) < .0001"), 'cue volume multiplies individual action gain');
    await sleep(700);
    check(await js('window.__playCalls === 3'), 'one short recording naturally repeats exactly three times');
    await js(`document.querySelector('#cueBoard [data-cue-id="p12-c1"]').click(); document.getElementById('stopAll').click(); window.__afterRepeatStop = window.__playCalls;`);
    await sleep(400);
    check(await js('window.__playCalls === window.__afterRepeatStop'), 'Stop All cancels remaining repeats');
    await js(`document.dispatchEvent(new KeyboardEvent('keydown', {key:'!'}));`);
    await sleep(40);
    check(await js('window.__playCalls >= 4'), 'named cue shortcut triggers from cue board');
    await js("document.getElementById('stopAll').click(); document.getElementById('editToggle').click(); document.querySelector('#cueBoard [data-cue-id=\"p12-c1\"]').click(); document.querySelector('.cue-delay').value = .3; document.getElementById('cueForm').requestSubmit()");
    await sleep(100);
    await js("document.getElementById('editToggle').click(); document.querySelector('#cueBoard [data-cue-id=\"p12-c1\"]').click(); window.__beforeStop = window.__playCalls; document.getElementById('stopAll').click()");
    await sleep(500);
    check(await js('window.__beforeStop === window.__playCalls'), 'Stop All cancels pending delayed actions');
    const setAction = async (kind, level) => {
      await js(`document.getElementById('editToggle').click(); document.querySelector('#cueBoard [data-cue-id="p12-c1"]').click();
        document.querySelector('.cue-kind').value = ${JSON.stringify(kind)}; document.querySelector('.cue-delay').value = 0;
        document.querySelector('.cue-level').value = ${level}; document.getElementById('cueForm').requestSubmit();`);
      await sleep(100);
      await js(`document.getElementById('editToggle').click(); document.querySelector('#cueBoard [data-cue-id="p12-c1"]').click()`);
      await sleep(100);
    };
    await setAction('loop', 50);
    await js('window.__loopPlays = window.__playCalls');
    await setAction('hold', 10);
    check(await js(`window.__playCalls === window.__loopPlays && Math.abs(window.__gains.at(-1).gain.value - .4) < .0001 && document.querySelector('#board .playing')`), 'continue loop preserves its playing instance and existing level');
    await setAction('fade', 50);
    await sleep(2100);
    check(await js(`!document.querySelector('#board .playing') && window.__gains.at(-1).gain.value < .001`), 'fade ramps down and stops playback');
    await js(`(async () => {
      window.__pulseBefore = window.browserProject.snapshot().pads.find(p => p.label === 'Test Pulse');
      const bytes = await (await fetch(window.browserProject.mediaUrl(window.__pulseBefore.sound))).arrayBuffer();
      const picked = await window.api.saveRecording(bytes), originalPick = window.api.pickMedia;
      window.api.pickMedia = async () => picked;
      document.getElementById('editToggle').click(); document.getElementById('padsView').click();
      document.querySelector('#board [data-id="' + window.__pulseBefore.id + '"]').click();
      document.getElementById('fSoundPick').click(); await new Promise(r => setTimeout(r, 50));
      window.api.pickMedia = originalPick; document.getElementById('editorForm').requestSubmit();
    })()`);
    await sleep(100);
    check(await js(`window.browserProject.snapshot().pads.find(p => p.id === window.__pulseBefore.id).sound !== window.__pulseBefore.sound && window.browserProject.snapshot().assignments['p12-c1'][0].padId === window.__pulseBefore.id`), 'replacing a recording preserves sound ID and cue links');
    await js(`document.getElementById('cuesView').click(); document.getElementById('editToggle').click()`);
    await js("document.getElementById('editToggle').click(); document.querySelector('#cueBoard [data-cue-id=\"p12-c1\"]').click(); document.getElementById('cueLive').checked = true; document.getElementById('cueName').value = 'Piano begins'; document.getElementById('cueForm').requestSubmit()");
    await sleep(100);
    await js("document.getElementById('editToggle').click(); window.__beforeLive = window.__playCalls; document.querySelector('#cueBoard [data-cue-id=\"p12-c1\"]').click()");
    await sleep(100);
    check(await js("window.__beforeLive === window.__playCalls && document.getElementById('toast').textContent.includes('Piano begins')"), 'live performer cue displays instruction without audio');
    await win.loadURL('http://127.0.0.1:8765');
    await js('window.browserProject.ready');
    await sleep(200);
    check(await js("window.browserProject.snapshot().pads.length === 65 && window.browserProject.getCue('p12-c1').name === 'Piano begins' && Object.values(window.browserProject.snapshot().passages).some(p => p.note === 'Pause here for the piano.')"), 'recordings, cues and notes survive browser reload');
    // Exercise an actual download, then re-import the saved bytes via the input's DOM files.
    const backupPath = path.join(results, 'test-backup.json');
    const downloadDone = new Promise((resolve, reject) => {
      win.webContents.session.once('will-download', (_event, item) => {
        item.setSavePath(backupPath);
        item.once('done', (_event, state) => state === 'completed' ? resolve() : reject(new Error('Backup download: ' + state)));
      });
    });
    await js("document.getElementById('exportBtn').click()");
    await downloadDone;
    const backup = JSON.parse(fs.readFileSync(backupPath, 'utf8'));
    check(backup.project.pads.length === 65 && backup.media.length >= 65, 'backup download contains edited project and audio');
    // Feed the selected file without opening an OS picker. Confirmation remains explicit in production.
    const feedBackup = async data => {
      const payload = JSON.stringify(JSON.stringify(data));
      await js(`(() => { window.confirm = () => true;
        const originalClick = HTMLInputElement.prototype.click;
        HTMLInputElement.prototype.click = function() {
          if (this.type !== 'file') return originalClick.call(this);
          HTMLInputElement.prototype.click = originalClick;
          const transfer = new DataTransfer(); transfer.items.add(new File([${payload}], 'backup.json', {type:'application/json'}));
          this.files = transfer.files; this.dispatchEvent(new Event('change'));
        }; document.getElementById('importBtn').click(); })()`);
    };
    const corrupt = structuredClone(backup); corrupt.media[0].sha256 = 'bad';
    await feedBackup(corrupt);
    await sleep(300);
    check(await js("document.getElementById('projectStatus').textContent.includes('Damaged backup') && window.browserProject.snapshot().pads.length === 65"), 'damaged backup rejected without overwriting current project');
    const reloadDone = new Promise(resolve => win.webContents.once('did-finish-load', resolve));
    await feedBackup(backup);
    await reloadDone;
    await js('window.browserProject.ready');
    await sleep(200);
    check(await js("window.browserProject.snapshot().pads.length === 65 && window.browserProject.getCue('p12-c1').name === 'Piano begins'"), 'verified backup restores successfully');
    await js("document.getElementById('padsView').click()");
    fs.writeFileSync(path.join(results, 'pads-preview.png'), (await win.webContents.capturePage()).toPNG());
    await js("document.getElementById('cuesView').click()");
    fs.writeFileSync(path.join(results, 'cues-preview.png'), (await win.webContents.capturePage()).toPNG());
    await js("document.getElementById('scriptView').click(); document.getElementById('scriptPage').value = '12'; document.getElementById('scriptPage').dispatchEvent(new Event('change'))");
    fs.writeFileSync(path.join(results, 'script-preview.png'), (await win.webContents.capturePage()).toPNG());
    check(errors.length === 0, 'no browser console errors: ' + errors.join('; '));
    log('ALL CHECKS PASSED'); finish(0);
  } catch (err) { log('FAIL ' + err.stack); finish(1); }
}).catch(err => { log('FAIL ' + err.stack); finish(1); });
